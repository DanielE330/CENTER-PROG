"""Generates deploy/compose/compose.yaml, deploy/compose/nats.conf and Quadlet
units from deploy/services.yaml. Run `make gen`; CI fails if the output differs
from what is committed.

Every service gets a cert-agent sidecar that obtains and renews its certificate
from step-ca into a tmpfs volume owned by the service's uid.
"""

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
UIDS = {"rust": 65532, "python": 10001, "advisor": 10001, "llm": 65532}
COMMON_PUBLISH = ["$JS.API.>", "$JS.ACK.>", "_INBOX.>", "ci.dlq.>"]
PYTHON_CMD = {"categorizer", "forecast", "connectors", "advisor"}
HEADER = "# Generated by deploy/gen.py from deploy/services.yaml. Do not edit by hand.\n"


def load() -> dict:
    return yaml.safe_load((ROOT / "services.yaml").read_text())


def hardening(uid: int, memory: str | None, read_only: bool = True) -> dict:
    out = {
        "user": f"{uid}:{uid}",
        "cap_drop": ["ALL"],
        "security_opt": ["no-new-privileges:true"],
        "read_only": read_only,
        "tmpfs": ["/tmp:size=64m"],
    }
    if memory:
        out["mem_limit"] = memory
    return out


def cert_agent(name: str, uid: int, lifetime: str, pkcs8: bool = False) -> dict:
    env = {"NAME": name, "LIFETIME": lifetime, "PKCS8": "true" if pkcs8 else "false"}
    return {
        "image": "smallstep/step-cli:0.31.0",
        "entrypoint": ["/bin/sh", "/agent/cert-agent.sh"],
        "environment": env,
        "volumes": [f"certs-{name}:/certs", "ca-public:/ca-public:ro", "../scripts:/agent:ro"],
        "secrets": ["provisioner_password"],
        "networks": ["app"],
        "depends_on": {"step-ca": {"condition": "service_started"}},
        "healthcheck": {"test": ["CMD", "test", "-s", "/certs/cert.pem"], "interval": "3s", "retries": 60},
        "restart": "unless-stopped",
        "mem_limit": "32m",
        **{k: v for k, v in hardening(uid, None).items() if k not in ("mem_limit",)},
    }


def service_env(name: str, spec: dict, allowed: list[str]) -> dict:
    env = {
        "SERVICE_NAME": name,
        "LISTEN_ADDR": "0.0.0.0:8443",
        "CERT_DIR": "/certs",
        "ALLOWED_CLIENTS": ",".join(allowed),
        "OIDC_ISSUER": "${PUBLIC_URL:-https://localhost:8443}/auth/realms/ci1",
        "OIDC_JWKS_URL": "https://keycloak:8443/auth/realms/ci1/protocol/openid-connect/certs",
        "OIDC_AUDIENCE": "ci1-api",
        "KEYCLOAK_INTERNAL_URL": "https://keycloak:8443/auth",
        "NATS_URL": "tls://nats:4222",
        "RUST_LOG": "info",
    }
    if spec.get("db"):
        scheme = "postgres" if spec["kind"] == "rust" else "postgresql"
        env["DATABASE_URL"] = f"{scheme}://{name}@postgres:5432/ci1"
    if name == "gateway":
        env["PUBLIC_URL"] = "${PUBLIC_URL:-https://localhost:8443}"
    if name == "connectors":
        env["DATA_DIR"] = "/data"
    if name == "llm-gateway":
        env["LLM_LOCAL_URL"] = "https://llm-local:8443/v1"
    if name == "advisor":
        env["AGENT_RUNTIME"] = "${AGENT_RUNTIME:-hermes}"
        env["HERMES_HOME"] = "/tmp/hermes"
    return env


def build_for(name: str, kind: str) -> dict:
    if kind == "rust":
        return {"context": "../..", "dockerfile": "deploy/docker/rust.Dockerfile", "args": {"SERVICE": name}}
    if kind == "python":
        return {"context": "../..", "dockerfile": "deploy/docker/python.Dockerfile", "args": {"SERVICE": name}}
    if kind == "advisor":
        return {"context": "../..", "dockerfile": "deploy/docker/advisor.Dockerfile"}
    raise ValueError(kind)


def healthcheck(name: str, kind: str) -> list[str]:
    if kind == "rust":
        return ["CMD", "/app/service", "--healthcheck"]
    return ["CMD", "/venv/bin/python", "-m", name, "--healthcheck"]


def compose(cfg: dict) -> dict:
    lifetime = cfg["defaults"]["cert_lifetime"]
    services: dict = {}
    volumes: dict = {
        "pgdata": {},
        "natsdata": {},
        "stepca": {},
        "kcdata": {},
        # Root certificate only; step-ca copies it here on every start.
        "ca-public": {
            "driver": "local",
            "driver_opts": {"type": "tmpfs", "device": "tmpfs", "o": "uid=1000,gid=1000,mode=0755,size=1m"},
        },
    }
    secrets_used: set[str] = {"provisioner_password", "keycloak_admin_password", "gateway_client_secret"}

    def certs_volume(name: str, uid: int) -> None:
        volumes[f"certs-{name}"] = {
            "driver": "local",
            "driver_opts": {"type": "tmpfs", "device": "tmpfs", "o": f"uid={uid},gid={uid},mode=0700,size=1m"},
        }

    # Infrastructure.
    infra = cfg["infra"]
    services["step-ca"] = {
        "image": infra["step-ca"]["image"],
        "entrypoint": ["/bin/sh", "/agent/step-ca.sh"],
        "environment": {"MAX_LIFETIME": lifetime},
        "volumes": ["stepca:/home/step", "ca-public:/ca-public", "../scripts:/agent:ro"],
        "secrets": ["provisioner_password"],
        "networks": ["app"],
        "restart": "unless-stopped",
        **hardening(infra["step-ca"]["uid"], "64m"),
        # The step-ca binary carries a file capability (cap_net_bind_service); the kernel refuses to
        # exec it when that capability is outside the bounding set or no-new-privileges is on.
        "cap_add": ["NET_BIND_SERVICE"],
        "security_opt": [],
    }
    for name in ("postgres", "nats", "keycloak", "caddy"):
        spec = infra[name]
        certs_volume(name, spec["uid"])
        services[f"cert-{name}"] = cert_agent(name, spec["uid"], lifetime, spec.get("cert", {}).get("pkcs8", False))
    services["postgres"] = {
        "image": infra["postgres"]["image"],
        "entrypoint": ["/bin/bash", "/etc/postgresql/entrypoint.sh"],
        "environment": {
            "POSTGRES_DB": "ci1",
            "POSTGRES_USER": "postgres",
            "POSTGRES_HOST_AUTH_METHOD": "trust",
            "PGDATA": "/var/lib/postgresql/data/pgdata",
        },
        "volumes": [
            "pgdata:/var/lib/postgresql/data",
            "certs-postgres:/certs:ro",
            "../scripts:/agent:ro",
            "../postgres/pg_hba.conf:/etc/postgresql/pg_hba.conf:ro",
            "../postgres/entrypoint.sh:/etc/postgresql/entrypoint.sh:ro",
            "../postgres/init.sh:/docker-entrypoint-initdb.d/10-roles.sh:ro",
        ],
        "networks": ["data"],
        "depends_on": {"cert-postgres": {"condition": "service_healthy"}},
        "healthcheck": {
            "test": ["CMD", "pg_isready", "-h", "/var/run/postgresql", "-U", "postgres"],
            "interval": "5s",
            "retries": 30,
        },
        "restart": "unless-stopped",
        **hardening(infra["postgres"]["uid"], infra["postgres"]["memory"]),
        "tmpfs": ["/tmp:size=64m", "/var/run/postgresql:size=1m,uid=999,gid=999"],
    }
    # Named volumes start root-owned; this one-shot hands the ones without an image-provided
    # directory to their service users. It can only chown and exits immediately.
    services["volume-init"] = {
        "image": "busybox:1.37.0",
        "command": ["sh", "-c", "chown -R 1000:1000 /nats /caddy"],
        "volumes": ["natsdata:/nats", "caddydata:/caddy"],
        "user": "0:0",
        "cap_drop": ["ALL"],
        "cap_add": ["CHOWN", "DAC_OVERRIDE", "FOWNER"],
        "security_opt": ["no-new-privileges:true"],
        "network_mode": "none",
        "restart": "no",
    }
    services["nats"] = {
        "image": infra["nats"]["image"],
        "entrypoint": ["/bin/sh", "/agent/nats-entrypoint.sh"],
        "volumes": [
            "natsdata:/data",
            "certs-nats:/certs:ro",
            "../scripts:/agent:ro",
            "./nats.conf:/etc/nats/nats.conf:ro",
        ],
        "networks": ["data"],
        "depends_on": {
            "cert-nats": {"condition": "service_healthy"},
            "volume-init": {"condition": "service_completed_successfully"},
        },
        "healthcheck": {
            "test": ["CMD", "wget", "-qO-", "http://127.0.0.1:8222/healthz"],
            "interval": "5s",
            "retries": 30,
        },
        "restart": "unless-stopped",
        **hardening(infra["nats"]["uid"], infra["nats"]["memory"]),
    }
    services["keycloak"] = {
        "image": infra["keycloak"]["image"],
        "entrypoint": ["/bin/bash", "/realm/entrypoint.sh"],
        "environment": {
            "KC_DB": "postgres",
            "KC_DB_URL": "jdbc:postgresql://postgres:5432/keycloak?ssl=true&sslmode=verify-full&sslrootcert=/certs/ca.pem&sslcert=/certs/cert.pem&sslkey=/certs/key.pk8",
            "KC_DB_USERNAME": "keycloak",
            "KC_HTTP_ENABLED": "false",
            "KC_HTTPS_PORT": "8443",
            "KC_HTTPS_CERTIFICATE_FILE": "/certs/cert.pem",
            "KC_HTTPS_CERTIFICATE_KEY_FILE": "/certs/key-pkcs8.pem",
            "KC_HTTPS_CERTIFICATES_RELOAD_PERIOD": "1h",
            "KC_HTTPS_CLIENT_AUTH": "request",
            "KC_TRUSTSTORE_PATHS": "/certs/ca.pem",
            "KC_HOSTNAME": "${PUBLIC_URL:-https://localhost:8443}/auth",
            "KC_HTTP_RELATIVE_PATH": "/auth",
            "KC_HOSTNAME_BACKCHANNEL_DYNAMIC": "true",
            "KC_PROXY_HEADERS": "xforwarded",
            "KC_HEALTH_ENABLED": "true",
            "KC_BOOTSTRAP_ADMIN_USERNAME": "admin",
            "PUBLIC_URL": "${PUBLIC_URL:-https://localhost:8443}",
            "JAVA_OPTS_KC_HEAP": "-XX:MaxRAMPercentage=65 -XX:InitialRAMPercentage=30",
        },
        "volumes": ["certs-keycloak:/certs:ro", "../keycloak:/realm:ro", "kcdata:/opt/keycloak/data"],
        "secrets": ["keycloak_admin_password", "gateway_client_secret"],
        "networks": ["app", "data"],
        "depends_on": {"cert-keycloak": {"condition": "service_healthy"}, "postgres": {"condition": "service_healthy"}},
        "healthcheck": {
            # The management interface speaks TLS too and the image has no curl: check the HTTPS port.
            "test": ["CMD-SHELL", "exec 3<>/dev/tcp/127.0.0.1/8443"],
            "interval": "10s",
            "retries": 40,
            "start_period": "60s",
        },
        "restart": "unless-stopped",
        # Quarkus re-augments into /opt/keycloak on start; the image cannot run read-only.
        **hardening(infra["keycloak"]["uid"], infra["keycloak"]["memory"], read_only=False),
    }
    services["caddy"] = {
        "image": "ci1/web:dev",
        "build": {"context": "../..", "dockerfile": "deploy/docker/web.Dockerfile"},
        "entrypoint": ["/bin/sh", "/caddy-entrypoint.sh"],
        "environment": {
            "PUBLIC_SITE": "${PUBLIC_URL:-https://localhost:8443}",
            "XDG_DATA_HOME": "/data",
            "XDG_CONFIG_HOME": "/config",
        },
        "volumes": [
            "certs-caddy:/certs:ro",
            "../scripts:/agent:ro",
            "../caddy/entrypoint.sh:/caddy-entrypoint.sh:ro",
            "../caddy/Caddyfile:/etc/caddy/Caddyfile:ro",
            "caddydata:/data",
        ],
        "ports": ["${PUBLIC_PORT:-8443}:8443"],
        "networks": ["edge", "app"],
        "depends_on": {
            "cert-caddy": {"condition": "service_healthy"},
            "gateway": {"condition": "service_healthy"},
            "volume-init": {"condition": "service_completed_successfully"},
        },
        "restart": "unless-stopped",
        **hardening(infra["caddy"]["uid"], infra["caddy"]["memory"]),
        "tmpfs": ["/tmp:size=16m", "/config:size=4m,uid=1000,gid=1000"],
    }
    volumes["caddydata"] = {}

    # Application services.
    for name, spec in cfg["services"].items():
        kind = spec["kind"]
        uid = UIDS[kind]
        certs_volume(name, uid)
        services[f"cert-{name}"] = cert_agent(name, uid, lifetime)
        if kind == "llm":
            services[f"cert-{name}"]["profiles"] = [spec["profile"]]
            services[name] = llm_local(spec, uid)
            continue
        for s in spec.get("secrets", []):
            secrets_used.add(s)
        depends = {
            f"cert-{name}": {"condition": "service_healthy"},
            "nats": {"condition": "service_healthy"},
            "keycloak": {"condition": "service_healthy"},
        }
        if spec.get("db"):
            depends["postgres"] = {"condition": "service_healthy"}
        svc = {
            "image": f"ci1/{name}:dev",
            "build": build_for(name, kind),
            "environment": service_env(name, spec, spec.get("clients", [])),
            "volumes": [f"certs-{name}:/certs:ro", *spec.get("volumes", [])],
            "secrets": spec.get("secrets", []),
            "networks": spec["networks"],
            "depends_on": depends,
            "healthcheck": {"test": healthcheck(name, kind), "interval": "10s", "retries": 30, "start_period": "20s"},
            "restart": "unless-stopped",
            **hardening(uid, spec.get("memory", "64m")),
        }
        if kind == "advisor":
            svc["tmpfs"] = ["/tmp:size=256m,uid=10001,gid=10001"]
        services[name] = svc

    services["seed"] = {
        "image": "ci1/connectors:dev",
        "command": ["/venv/bin/python", "-m", "connectors", "--seed"],
        "environment": service_env("connectors", cfg["services"]["connectors"], []),
        "volumes": ["certs-connectors:/certs:ro", *cfg["services"]["connectors"].get("volumes", [])],
        "secrets": ["counterparty_hmac_key", "demo_password"],
        "networks": ["app", "data"],
        "depends_on": {
            "connectors": {"condition": "service_healthy"},
            "tenancy": {"condition": "service_healthy"},
            "ingest": {"condition": "service_healthy"},
            "obligations": {"condition": "service_healthy"},
        },
        "profiles": ["seed"],
        "restart": "no",
        **hardening(UIDS["python"], "256m"),
    }
    networks = {
        "edge": {},
        "app": {"internal": True},
        "data": {"internal": True},
        "egress": {},
        "llm": {"internal": True},
    }
    secrets = {s: {"file": f"../dev-secrets/{s}"} for s in sorted(secrets_used)}
    return {"name": "ci1", "services": services, "networks": networks, "volumes": volumes, "secrets": secrets}


