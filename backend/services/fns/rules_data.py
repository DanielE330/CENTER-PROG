"""Правила налогового календаря в виде данных по годам.

ВАЖНО: проверить на актуальный год до включения. Сроки и размеры взносов меняются законами; поле status
показывает, насколько год проверен:
  checked_against_site : сроки сверены с окном календаря nalog.gov.ru на дату checked_at (за окно, не за весь год);
  verify               : правила перенесены с предыдущего года или известны по НК РФ, но на сайте ФНС ещё не сверены.
Суммы налогов не считаем. Исключение: фиксированные страховые взносы ИП установлены законом (ст. 430 НК РФ),
они лежат здесь как данные, с пометкой verify.
Формат дат: (месяц, день). Если срок выпадает на нерабочий день, он переносится на ближайший рабочий (ст. 6.1 НК РФ).
"""

REGIMES = ("usn_income", "usn_income_expense", "osno", "eshn", "ausn", "npd", "patent")


def _year(fixed_kop: int, status: str, checked_at: str | None = None, note: str = "") -> dict:
    return {
        "status": status, "checked_at": checked_at, "note": note,
        "enp": {"day": 28},                                   # ст. 58 НК РФ: ЕНП вносится до 28-го числа
        "usn": {"advance": {4: "Q1", 7: "H1", 10: "9M"}, "advance_day": 28,          # ст. 346.21 НК РФ
                "annual": {"org": (3, 28), "ip": (4, 28)}},                           # ст. 346.23 НК РФ, за предыдущий год
        "nds": {"day": 28, "installments": 3},                                        # ст. 174 НК РФ
        "profit": {"advance": {4: "Q1", 7: "H1", 10: "9M"}, "advance_day": 28, "annual": (3, 28)},  # ст. 287, 289 НК РФ
        "ndfl_ip": {"advance": {4: "Q1", 7: "H1", 10: "9M"}, "advance_day": 28, "annual": (7, 15)},  # ст. 227 НК РФ
        "eshn": {"advance": (7, 28), "annual": {"org": (3, 28), "ip": (4, 28)}},      # ст. 346.9 НК РФ
        "ausn": {"day": 25},                                  # налог за прошлый месяц до 25-го (ст. 346.56 НК РФ)
        "npd": {"day": 28},                                   # налог на профессиональный доход, до 28-го месяца-следующего
        "insurance_ip": {"fixed_kop": fixed_kop, "fixed_due": (12, 31),               # ст. 432 НК РФ
                         "one_percent_due": (7, 1),                                    # ст. 430 НК РФ, за предыдущий год
                         "one_percent_threshold_kop": 30_000_000},
    }


RULES = {
    2024: _year(4_950_000, "verify", note="фиксированные взносы ИП за 2024 год: 49 500 руб."),
    2025: _year(5_365_800, "verify", note="фиксированные взносы ИП за 2025 год: 53 658 руб."),
    2026: _year(5_739_000, "checked_against_site", "2026-10-24",
                note="сроки ЕНП, НДС и УСН сверены с окном календаря nalog.gov.ru (сентябрь-декабрь 2026); "
                     "фиксированные взносы ИП за 2026 год (57 390 руб.) проверить"),
}
MIN_YEAR, MAX_YEAR = 2023, 2035


def rules_for(year: int) -> tuple[dict, int, bool]:
    """(правила, год правил, это точное попадание?). Для лет вне таблицы берём ближайший известный."""
    if year in RULES:
        return RULES[year], year, True
    known = sorted(RULES)
    use = max((y for y in known if y <= year), default=known[0])
    return RULES[use], use, False
