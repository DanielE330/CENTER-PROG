"""Категоризация операций по назначению платежа: правила + confidence.

Правила — первый уровень (baseline); ML-классификатор можно подключить позже
за тем же интерфейсом categorize(purpose, direction) -> (category, confidence).
Порядок правил важен: первое подошедшее выигрывает; направление разводит смысл.
"""
import re
from functools import lru_cache

# шаблонные хвосты про НДС не должны влиять на категорию («Без налога (НДС)» ≠ налоги)
_VAT_NOISE = re.compile(
    r"без налога\s*\(ндс\)|ндс не облагается|без ндс|(?:в том числе|в т\.\s?ч\.)\s*ндс.*|сумма\s+\d.*$",
    re.I,
)

# (категория, направление или None, regex, confidence)
RULES: list[tuple[str, str | None, str, float]] = [
    # --- собственные средства / владелец
    ("transfers", None, r"перевод собственных|между своими счетами|внутренний перевод|пополнение счета собственными|взнос в уставный|"
                        r"перевод на личн|на личную карту|на счет физического лица|на счёт физического лица|"
                        r"закрытием счета|закрытием счёта(?!.*овердрафт)|перечисление остатка", 0.9),
    ("transfers", "out", r"дивиденд", 0.85),
    # --- возвраты ошибочных платежей
    ("refunds", "in", r"возврат платежа|неверно указан|ошибочн", 0.9),
    ("refunds", "out", r"возврат платежа|возврат ошибочн|возврат средств покупател|возврат (?:денежных )?средств", 0.85),
    # --- налоги
    ("taxes", "out", r"\bенп\b|единый налоговый плат[её]ж|поручению налогового|налог(?!а\b)|\bусн\b|\bндфл\b|\bндс\b|страховые взносы|"
                      r"взнос.{0,20}(пфр|сфр|фнс)|\bифнс\b|\bфнс\b|\bпфр\b|\bсфр\b|штраф", 0.95),
    # --- кредиты / займы / лизинг (в обе стороны)
    ("loans", None, r"кредит|займ|проценты|процентов|овердрафт|погашение.{0,15}(долг|основн)|основной долг|лизинг", 0.9),
    # --- зарплата и ГПХ
    ("payroll", "out", r"зарплат|заработн|аванс.{0,15}(сотрудник|работник)|оплата труда|выплата.{0,10}персонал|договор[уа]? гпх|\bгпх\b|самозанят", 0.95),
    # --- эквайринг/POS (комиссионные) раньше аренды
    ("bank_fees", "out", r"аренд\w* pos|pos-терминал|комисси|обслуживание счета|обслуживание счёта|\bрко\b|эквайринг|ведение счета", 0.9),
    ("rent", "out", r"аренд|субаренд", 0.95),
    ("utilities", "out", r"коммунал|электроэнерг|водоснабж|водоотвед|вывоз тко|\bтко\b|интернет|услуг\w* связи|\bсвязь\b|телефон|хостинг|облачн|подписк|право использования по|"
                          r"теплоснабж|отоплен|газоснабж", 0.85),
    ("marketing", "out", r"реклам|продвижени|маркетинг|яндекс\.?\s?директ|\bvk\b|таргет", 0.9),
    # --- выручка (поступления)
    ("revenue", "in", r"эквайринг|сбп|взнос наличных|инкассирован|торговая выручка|выручк|договору оферты|агентск|гарантийн|"
                       r"оплата|предоплата|доплата|окончательный расч[её]т|авансовый платеж|аванс|поступлени|реализац|за товар|за услуг|перечисление денежных средств", 0.85),
    ("other_income", "in", r"субсиди|грант|страхового возмещения|возмещени", 0.8),
    # --- расходы на закупки
    ("suppliers", "out", r"оплата|предоплат|доплата|аванс|окончательный расч[её]т|пополнение|поставк|закупк|за товар|за материал|сырь[её]|топливн|провоз|договор", 0.75),
    ("other_expense", "out", r"исполнительн|списание по", 0.6),
]
_COMPILED = [(c, d, re.compile(p, re.I), conf) for c, d, p, conf in RULES]


@lru_cache(maxsize=65536)
def categorize(purpose: str, direction: str) -> tuple[str, float]:
    text = _VAT_NOISE.sub(" ", purpose or "")
    for cat, d, rx, conf in _COMPILED:
        if d and d != direction:
            continue
        if rx.search(text):
            return cat, conf
    return ("other_income" if direction == "in" else "other_expense"), 0.2
